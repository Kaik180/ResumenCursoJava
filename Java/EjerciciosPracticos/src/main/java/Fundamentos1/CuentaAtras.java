package Fundamentos1;

public class CuentaAtras {
    public static void main(String[] args) {
        System.out.println("Iniciando lanzamiento...");

        // El bucle empieza en 5 y va restando 1 (i--) en cada vuelta mientras i sea mayor que 0
        for (int i = 5; i > 0; i--) {
            System.out.println(i + "...");
        }

        System.out.println("¡Despegue! 🚀");
    }
}
